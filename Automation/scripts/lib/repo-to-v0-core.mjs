import { existsSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  PATRON_FEED_SCOPES,
  RELAY_TOKENS_EXCERPT_LABEL,
} from './patron-feed-bundle-manifest.mjs'
import {
  copyBlockMaxCharsFromEnv,
  truncateCopyBlock,
} from './pull-v0-copy-block-core.mjs'

const AIRTABLE_API = 'https://api.airtable.com/v0'

const __dirname = dirname(fileURLToPath(import.meta.url))

export function resolveRepoRoot() {
  // Automation/scripts/lib → Automation → Rescue root
  return resolve(__dirname, '..', '..', '..')
}

function guessFence(path) {
  const p = path.toLowerCase()
  if (p.endsWith('.tsx')) return 'tsx'
  if (p.endsWith('.ts')) return 'ts'
  if (p.endsWith('.jsx')) return 'jsx'
  if (p.endsWith('.js')) return 'js'
  if (p.endsWith('.css')) return 'css'
  if (p.endsWith('.json')) return 'json'
  if (p.endsWith('.md')) return 'md'
  return 'text'
}

function requireEnv(name) {
  const v = process.env[name]
  if (!v?.trim()) throw new Error(`Missing required env: ${name}`)
  return v.trim()
}

/**
 * Pull Relay CSS custom properties used by patron feed surfaces.
 */
export function extractRelayTokensExcerpt(repoRoot) {
  const cssPath = join(repoRoot, 'web/app/globals.css')
  const raw = readFileSync(cssPath, 'utf8')
  const start = raw.indexOf('/* Full-page auth / onboarding')
  const end = raw.indexOf('/* Site Designer (v0 copy block)')
  if (start === -1 || end === -1 || end <= start) {
    return [
      '/* relay-tokens-excerpt: could not auto-extract; see web/app/globals.css */',
      ':root {',
      '  --relay-bg: #0a0a0a;',
      '  --relay-electric: #00aa6f;',
      '}',
    ].join('\n')
  }
  return [
    '/* Excerpt from web/app/globals.css — Relay patron feed tokens */',
    raw.slice(start, end).trim(),
  ].join('\n\n')
}

function defaultEditTask(scope) {
  if (scope === 'production') {
    return 'Refine the production patron feed (`RelayApp` at `/patron/feed`) while preserving component names, prop contracts, and file paths.'
  }
  return 'Refine the patron home feed layout and feed cards while preserving component names, prop contracts, and file paths.'
}

export function buildEditPreamble({ target, scope, editTask, includeLarge, omitted }) {
  const scopeMeta = PATRON_FEED_SCOPES[scope]
  const task = (editTask || '').trim() || defaultEditTask(scope)
  const omittedNote =
    omitted.length > 0
      ? `\n- **Omitted (re-add with --include-large):** ${omitted.join(', ')}`
      : ''

  return [
    '## Context',
    '',
    '- **Product**: Relay (patron home / feed)',
    `- **Target**: ${target}`,
    `- **Scope**: ${scope} — ${scopeMeta.description}`,
    '- **Mode**: Edit existing implementation in place — **do not** regenerate from scratch or invent a new product.',
    '',
    '## Edit task',
    '',
    task,
    '',
    '## Rules (Strategy A — v0 preview)',
    '',
    '- Preserve file paths, exports, and TypeScript prop shapes unless the edit task says otherwise.',
    '- For the **v0 hosted preview only**: do **not** add required `NEXT_PUBLIC_*` env vars. Use inline mocks / `relay-fixtures` / `patron-relay-feed-bundle.json`.',
    '- **Single pass**: one visual direction; no competing layout paradigms.',
    '- Mock `@/lib/relay-api` calls in preview if that file was omitted from the bundle.',
    omittedNote,
    '',
    '## Existing source files',
    '',
    'Edit the files below. Return updated files in the same paths.',
    '',
    '---',
    '',
  ].join('\n')
}

/**
 * @param {{ target: string; scope: string; files: { name: string; content: string }[]; editTask?: string; includeLarge?: boolean; omitted?: string[] }} opts
 */
export function formatRepoSourceBundle(opts) {
  const {
    target,
    scope,
    files,
    editTask,
    includeLarge = false,
    omitted = [],
  } = opts
  const generatedAt = new Date().toISOString()

  const header = [
    `<!-- Auto-generated by repo-to-v0 — paste into v0 or Production Ledger Prompt Draft -->`,
    '',
    `# Relay repo source bundle`,
    '',
    `- **target:** ${target}`,
    `- **scope:** ${scope}`,
    `- **files:** ${files.length}`,
    `- **includeLarge:** ${includeLarge}`,
    `- **generatedAt:** ${generatedAt}`,
    '',
    '---',
    '',
  ].join('\n')

  const preamble = buildEditPreamble({ target, scope, editTask, includeLarge, omitted })

  let body = ''
  for (const f of files) {
    const name = f.name || '(unnamed)'
    const content = typeof f.content === 'string' ? f.content : ''
    body += `## ${name}\n\n\`\`\`${guessFence(name)}\n${content}\n\`\`\`\n\n`
  }

  return header + preamble + body
}

/**
 * @param {{ scope: string; includeLarge?: boolean; repoRoot?: string }} opts
 */
export function collectPatronFeedFiles(opts) {
  const repoRoot = opts.repoRoot || resolveRepoRoot()
  const scope = opts.scope || 'visual'
  const includeLarge = Boolean(opts.includeLarge)
  const scopeMeta = PATRON_FEED_SCOPES[scope]
  if (!scopeMeta) {
    throw new Error(`Unknown scope "${scope}". Use: ${Object.keys(PATRON_FEED_SCOPES).join(', ')}`)
  }

  const paths = [...scopeMeta.files]
  const omitted = [...(scopeMeta.omitByDefault || [])]
  if (includeLarge) {
    for (const p of omitted) {
      if (!paths.includes(p)) paths.push(p)
    }
    omitted.length = 0
  }

  /** @type {{ name: string; content: string }[]} */
  const files = []
  const missing = []

  for (const rel of paths) {
    const abs = join(repoRoot, rel)
    if (!existsSync(abs)) {
      missing.push(rel)
      continue
    }
    files.push({ name: rel.replace(/\\/g, '/'), content: readFileSync(abs, 'utf8') })
  }

  files.push({
    name: RELAY_TOKENS_EXCERPT_LABEL,
    content: extractRelayTokensExcerpt(repoRoot),
  })

  return { files, missing, omitted: includeLarge ? [] : [...(scopeMeta.omitByDefault || [])] }
}

/**
 * @param {{ scope?: string; includeLarge?: boolean; editTask?: string; maxChars?: number; repoRoot?: string }} opts
 */
export function buildPatronFeedBundle(opts = {}) {
  const scope = opts.scope || 'visual'
  const includeLarge = Boolean(opts.includeLarge)
  const { files, missing, omitted } = collectPatronFeedFiles({
    scope,
    includeLarge,
    repoRoot: opts.repoRoot,
  })

  const text = formatRepoSourceBundle({
    target: 'patron-feed',
    scope,
    files,
    editTask: opts.editTask,
    includeLarge,
    omitted,
  })

  const maxChars = opts.maxChars ?? copyBlockMaxCharsFromEnv()
  const truncated = text.length > maxChars
  const forAirtable = truncated ? truncateCopyBlock(text, maxChars) : text

  return {
    scope,
    includeLarge,
    files,
    missing,
    omitted,
    text,
    forAirtable,
    truncated,
    charCount: text.length,
    airtableCharCount: forAirtable.length,
  }
}

export async function airtablePatchPromptDraft(baseId, tableId, recordId, promptDraft) {
  const token = requireEnv('AIRTABLE_API_KEY')
  const url = `${AIRTABLE_API}/${baseId}/${tableId}`
  const res = await fetch(url, {
    method: 'PATCH',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      records: [{ id: recordId, fields: { 'Prompt Draft': promptDraft } }],
    }),
  })
  if (!res.ok) {
    const body = await res.text()
    throw new Error(`Airtable patch (Prompt Draft) failed: ${res.status} ${body}`)
  }
  return res.json()
}
